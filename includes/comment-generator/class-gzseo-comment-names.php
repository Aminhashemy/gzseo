    /**
     * Get random name
     * 
     * @param string $gender Optional. 'male', 'female', or null for random
     * @return array
     */
    public function get_random_name($gender = null) {
        // Determine gender if not specified
        if (!$gender) {
            $gender = wp_rand(0, 1) ? 'male' : 'female';
        }
        
        // Get first name based on gender
        if ($gender === 'male') {
            $first_name = $this->male_names[array_rand($this->male_names)];
        } else {
            $first_name = $this->female_names[array_rand($this->female_names)];
        }
        
        // Get random last name
        $last_name = $this->last_names[array_rand($this->last_names)];
        
        // Create full name
        $full_name = $first_name . ' ' . $last_name;
        
        return array(
            'first_name' => $first_name,
            'last_name' => $last_name,
            'full_name' => $full_name,
            'gender' => $gender
        );
    }
    
    /**
     * Detect gender from name
     * 
     * @param string $name
     * @return string 'male', 'female', or 'unknown'
     */
    public function detect_gender($name) {
        // Extract first name
        $parts = explode(' ', $name);
        $first_name = $parts[0];
        
        // Check in male names
        if (in_array($first_name, $this->male_names)) {
            return 'male';
        }
        
        // Check in female names
        if (in_array($first_name, $this->female_names)) {
            return 'female';
        }
        
        return 'unknown';
    }
    
